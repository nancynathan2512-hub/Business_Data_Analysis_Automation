import pandas as pd
from pathlib import Path

# --------------------------------------------------
# PATHS
# --------------------------------------------------

BASE_DIR = Path(__file__).resolve().parent.parent

INPUT_FILE = BASE_DIR / "Data" / "Cleaned Data" / "cleaned_retail_data.xlsx"
OUTPUT_FILE = BASE_DIR / "Data" / "Cleaned Data" / "transformed_retail_data.xlsx"


# --------------------------------------------------
# START
# --------------------------------------------------

print("=" * 60)
print("BUSINESS DATA TRANSFORMATION STARTED")
print("=" * 60)

print(f"\nInput file:")
print(INPUT_FILE)

print(f"\nOutput file:")
print(OUTPUT_FILE)


# --------------------------------------------------
# LOAD CLEANED DATA
# --------------------------------------------------

print("\nLoading cleaned workbook...")

sheets = pd.read_excel(INPUT_FILE, sheet_name=None)

print(f"Sheets found: {list(sheets.keys())}")


# --------------------------------------------------
# COMBINE SHEETS
# --------------------------------------------------

print("\nCombining cleaned sheets...")

data = pd.concat(sheets.values(), ignore_index=True)

print(f"Total rows: {len(data):,}")


# --------------------------------------------------
# DATA TYPES
# --------------------------------------------------

print("\nPreparing data types...")

data["InvoiceDate"] = pd.to_datetime(
    data["InvoiceDate"],
    errors="coerce"
)

data["Quantity"] = pd.to_numeric(
    data["Quantity"],
    errors="coerce"
)

data["Price"] = pd.to_numeric(
    data["Price"],
    errors="coerce"
)


# --------------------------------------------------
# BUSINESS METRICS
# --------------------------------------------------

print("\nCreating business metrics...")

# Revenue generated by each transaction
data["Revenue"] = data["Quantity"] * data["Price"]

# Year
data["Year"] = data["InvoiceDate"].dt.year

# Month
data["Month"] = data["InvoiceDate"].dt.month

# Month name
data["Month_Name"] = data["InvoiceDate"].dt.month_name()

# Year-Month for reporting
data["Year_Month"] = data["InvoiceDate"].dt.to_period("M").astype(str)

# Day of week
data["Day_Name"] = data["InvoiceDate"].dt.day_name()


# --------------------------------------------------
# SORT DATA
# --------------------------------------------------

print("\nSorting transactions by date...")

data = data.sort_values(
    by="InvoiceDate"
).reset_index(drop=True)


# --------------------------------------------------
# SAVE TRANSFORMED DATA
# --------------------------------------------------

print("\nSaving transformed data...")

data.to_excel(
    OUTPUT_FILE,
    index=False,
    sheet_name="Transformed Data"
)


# --------------------------------------------------
# COMPLETE
# --------------------------------------------------

print("\n" + "=" * 60)
print("TRANSFORMATION COMPLETE")
print("=" * 60)

print(f"\nRows created: {len(data):,}")
print(f"Columns created: {len(data.columns)}")

print("\nNew business columns:")
print("- Revenue")
print("- Year")
print("- Month")
print("- Month_Name")
print("- Year_Month")
print("- Day_Name")

print(f"\nTransformed file created at:")
print(OUTPUT_FILE)
